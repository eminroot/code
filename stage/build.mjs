// Bundles the 3D stage into one self-contained HTML page.
// Outputs src/stage/stage-html.ts for the app and stage/dev/index.html for the browser.
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const result = await build({
  entryPoints: [path.join(here, 'src/main.js')],
  bundle: true, minify: true, format: 'iife', target: ['safari15'], write: false, legalComments: 'none',
});
const js = result.outputFiles[0].text;
const css = 'html,body{margin:0;height:100%;overflow:hidden;touch-action:none;-webkit-user-select:none;user-select:none;-webkit-tap-highlight-color:transparent;background:radial-gradient(120% 90% at 50% 25%,#F2FAFF 0%,#DDF4FF 55%,#C6EBFF 100%)}canvas{display:block;width:100%;height:100%;outline:none}';
const page = (extra = '') => `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no"><style>${css}</style></head><body>${extra}<script>${js.replace(/<\/script/g, '<\/script')}</script></body></html>`;

fs.mkdirSync(path.join(root, 'src/stage'), { recursive: true });
fs.writeFileSync(path.join(root, 'src/stage/stage-html.ts'), '// Generated by stage/build.mjs. Do not edit.\nexport const STAGE_HTML = ' + JSON.stringify(page()) + ';\n');
fs.mkdirSync(path.join(here, 'dev'), { recursive: true });
fs.writeFileSync(path.join(here, 'dev/stage.html'), page('<script>window.__assetBase="../../assets/";window.__onStage=function(m){(window.__log=window.__log||[]).push(m);if(m.type==="error")console.error(m.message)}</script>'));
console.log('stage bundle', (js.length / 1024).toFixed(0) + 'KB');
